// Guardrail Agent — Safety, compliance, and output validation

function analyze(triageResult, diagnosticResult, medicationResult) {
  const steps = [];
  const disclaimers = [];
  const safetyFlags = [];
  let overallRisk = 'low';

  steps.push({ action: 'Initiating safety review', detail: 'Scanning all agent outputs for compliance' });

  // Check triage
  if (triageResult) {
    if (triageResult.triageLevel === 'Emergency') {
      safetyFlags.push({ level: 'CRITICAL', message: 'Emergency triage level — ensure immediate clinical oversight', action: 'HUMAN_REVIEW_REQUIRED' });
      overallRisk = 'critical';
    } else if (triageResult.triageLevel === 'Urgent') {
      safetyFlags.push({ level: 'HIGH', message: 'Urgent case — prompt physician review required', action: 'EXPEDITE_REVIEW' });
      overallRisk = 'high';
    }
    steps.push({ action: 'Triage safety check', detail: `Level: ${triageResult.triageLevel} → Risk: ${overallRisk}` });
  }

  // Check diagnostics
  if (diagnosticResult && diagnosticResult.primaryDiagnosis) {
    const primary = diagnosticResult.primaryDiagnosis;
    if (primary.confidence < 40) {
      safetyFlags.push({ level: 'WARNING', message: `Low diagnostic confidence (${primary.confidence}%) — additional workup strongly recommended`, action: 'RECOMMEND_WORKUP' });
      if (overallRisk === 'low') overallRisk = 'moderate';
    }
    if (primary.severity === 'critical') {
      safetyFlags.push({ level: 'CRITICAL', message: `Primary diagnosis (${primary.condition}) is a critical condition`, action: 'HUMAN_REVIEW_REQUIRED' });
      overallRisk = 'critical';
    }
    if (diagnosticResult.differentialDiagnoses && diagnosticResult.differentialDiagnoses.length >= 3) {
      const topTwo = diagnosticResult.differentialDiagnoses.slice(0, 2);
      if (topTwo[1] && topTwo[0].confidence - topTwo[1].confidence < 15) {
        safetyFlags.push({ level: 'WARNING', message: 'Close differential — top diagnoses have similar confidence scores', action: 'RECOMMEND_FURTHER_TESTING' });
      }
    }
    steps.push({ action: 'Diagnostic safety check', detail: `${safetyFlags.length} flags raised` });
  }

  // Check medications
  if (medicationResult) {
    if (medicationResult.allergyWarnings && medicationResult.allergyWarnings.length > 0) {
      safetyFlags.push({ level: 'CRITICAL', message: `${medicationResult.allergyWarnings.length} allergy conflict(s) detected in medication plan`, action: 'BLOCK_PRESCRIPTION' });
      overallRisk = 'critical';
    }
    if (medicationResult.drugInteractions && medicationResult.drugInteractions.length > 0) {
      const majorInteractions = medicationResult.drugInteractions.filter(i => i.severity === 'major' || i.severity === 'contraindicated');
      if (majorInteractions.length > 0) {
        safetyFlags.push({ level: 'HIGH', message: `${majorInteractions.length} major drug interaction(s) require review`, action: 'PHARMACIST_REVIEW' });
        if (overallRisk !== 'critical') overallRisk = 'high';
      }
    }
    steps.push({ action: 'Medication safety check', detail: `Drug interactions and allergies validated` });
  }

  // Standard disclaimers
  disclaimers.push('This analysis is generated by an AI system and is intended for clinical decision support only.');
  disclaimers.push('All recommendations should be validated by a licensed healthcare professional before clinical action.');
  disclaimers.push('This system does not constitute medical advice, diagnosis, or treatment.');
  disclaimers.push('Patient-specific factors not captured in this analysis may alter clinical recommendations.');

  if (overallRisk === 'critical' || overallRisk === 'high') {
    disclaimers.push('⚠️ HIGH-RISK CASE: Mandatory physician review before any clinical action.');
  }

  steps.push({ action: 'Guardrail review complete', detail: `Overall risk: ${overallRisk} | ${safetyFlags.length} safety flags | ${disclaimers.length} disclaimers` });

  const riskColorMap = { low: '#10b981', moderate: '#3b82f6', high: '#f59e0b', critical: '#ef4444' };

  return {
    agent: 'Guardrail Agent',
    icon: '🛡️',
    overallRisk,
    riskColor: riskColorMap[overallRisk],
    safetyFlags,
    disclaimers,
    humanReviewRequired: overallRisk === 'critical' || overallRisk === 'high',
    reasoning: steps,
    recommendation: safetyFlags.length > 0
      ? `${safetyFlags.length} safety concern(s) identified. Risk level: ${overallRisk.toUpperCase()}. ${overallRisk === 'critical' ? 'MANDATORY physician review.' : 'Review recommended.'}`
      : `All outputs passed safety review. Risk level: ${overallRisk.toUpperCase()}.`
  };
}

module.exports = { analyze };
